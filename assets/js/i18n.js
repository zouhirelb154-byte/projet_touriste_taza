function updateLanguageButtons() {
  document.querySelectorAll(".lang-btn").forEach((button) => {
    const isActive = button.dataset.lang === currentLang;

    button.classList.toggle("bg-darkgreen", isActive);
    button.classList.toggle("text-white", isActive);
    button.classList.toggle("hover:bg-olive", isActive);

    button.classList.toggle("border", !isActive);
    button.classList.toggle("border-darkgreen", !isActive);
    button.classList.toggle("text-darkgreen", !isActive);
    button.classList.toggle("hover:border-gold", !isActive);
    button.classList.toggle("hover:text-gold", !isActive);
  });
}

function switchLanguage(lang) {
  currentLang = translations[lang] ? lang : "fr";
  localStorage.setItem("visitTazaLanguage", currentLang);

  document.documentElement.lang = currentLang;
  document.documentElement.dir = currentLang === "ar" ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n], [data-footer-i18n]").forEach((element) => {
    const key = element.dataset.i18n || element.dataset.footerI18n;

    if (translations[currentLang][key] || translations.fr[key]) {
      element.textContent = t(key);
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.setAttribute("placeholder", t(element.dataset.i18nPlaceholder));
  });

  updateLanguageButtons();
  document.dispatchEvent(new CustomEvent("visitTaza:languageChanged", { detail: { lang: currentLang } }));
}

function updateWeatherCard() {
  const temp = 22 + Math.floor(Math.random() * 7);
  const humidity = 35 + Math.floor(Math.random() * 16);
  const wind = 5 + Math.floor(Math.random() * 8);

  const tempEl = document.getElementById("weather-temp");
  const humidityEl = document.getElementById("weather-humidity");
  const windEl = document.getElementById("weather-wind");

  if (tempEl) tempEl.textContent = temp;
  if (humidityEl) humidityEl.textContent = humidity;
  if (windEl) windEl.textContent = wind;
}

document.addEventListener("DOMContentLoaded", () => {
  switchLanguage(currentLang);
  updateWeatherCard();
  setInterval(updateWeatherCard, 8000);

  document.querySelectorAll(".lang-btn").forEach((button) => {
    button.addEventListener("click", () => switchLanguage(button.dataset.lang));
  });
});
